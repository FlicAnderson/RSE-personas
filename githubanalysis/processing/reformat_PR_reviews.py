    def save_formatted_PR_reviews(self, out_filename="processed-PR-reviews"):
        """
        Save the reformatted PR reviews data out to csv file.
        """

        write_out = f"{self.data_location/out_filename}_{self.sanitised_repo_name}_{self.current_date_info}.csv"

        if self.reformatted_PR_reviews is not None:
            self.reformatted_PR_reviews.to_csv(
                path_or_buf=write_out, mode="w", index=True, header=True
            )
            self.logger.info(
                f"wrote out dataframe of PR reviews to file {write_out} for repo {self.repo_name}"
            )
        else:
            raise RuntimeError(
                f"Error: Failed saving reformatted PR Reviews data out to {write_out}. Run reformat_PR_reviews*() function."
            )
